EVAL_KEYS = ["accuracy", "mean_reward", "std_reward", "avg_output_tokens", "count_correct", "count_partial", "count_failed"]


def evaluate_model(llm: FlexLLM, sampling_params: SamplingParams, eval_prompts: List[str], eval_answers: List[Dict]) -> Dict[str, Any]:
    rollouts = llm.generate(eval_prompts, sampling_params)
    examples, rewards, output_token_lengths = [], [], []
    for rollout, gt in zip(rollouts, eval_answers):
        out = rollout.outputs[0]
        reward_value = reward_fn(out.text, gt)
        equation = _extract_answer(out.text)
        result = _evaluate_equation(equation) if equation is not None else None
        output_token_lengths.append(len(out.token_ids))
        examples.append({"prompt": rollout.prompt, "response": out.text, "answer": gt, "equation": equation,
                         "result": result, "reward": reward_value, "output_tokens": len(out.token_ids)})
        rewards.append(reward_value)
    rewards_tensor = torch.tensor(rewards) if rewards else torch.tensor([0.0])
    tol = 1e-8
    count_correct = sum(1 for r in rewards if abs(r - 1.0) < tol)
    count_partial = sum(1 for r in rewards if abs(r - 0.1) < tol)
    count_failed = sum(1 for r in rewards if abs(r - 0.0) < tol)
    return {
        "mean_reward": float(rewards_tensor.mean().item()),
        "std_reward": float(rewards_tensor.std().item()) if rewards_tensor.numel() > 1 else 0.0,
        "num_examples": len(rewards), "examples": examples, "count_correct": count_correct,
        "count_partial": count_partial, "count_failed": count_failed,
        "accuracy": (count_correct / len(rewards)) * 100 if rewards else 0.0,
        "avg_output_tokens": sum(output_token_lengths) / max(len(output_token_lengths), 1),
    }


def _format_eval_example(example: Dict[str, Any]) -> str:
    answer = example.get("answer") if isinstance(example.get("answer"), dict) else {}
    return (f"Prompt: {example.get('prompt', '')}\n"
            f"Response: {example.get('response', '')}\n"
            f"Equation: {example.get('equation')} | Result: {example.get('result')} | Target: {answer.get('target', '?')} "
            f"| Numbers: {answer.get('numbers')}\n"
            f"Reward: {example.get('reward', 0.0):.3f}\n")


def log_train(stats: Dict[str, float], writer: SummaryWriter, step: int) -> None:
    for k, v in stats.items():
        writer.add_scalar(f"train/{k}", float(v), global_step=step)
    with open(os.path.join(writer.get_logdir(), "train_metrics.jsonl"), "a") as f:
        f.write(json.dumps({"step": step, **{k: float(v) for k, v in stats.items()}}) + "\n")
    print(f"Step {step} | Loss: {stats['loss']:.4f} | Grad norm: {stats['grad_norm']:.4f} | "
          f"Reward mean: {stats['reward_mean']:.4f} | Reward std: {stats['reward_std']:.4f} | "
          f"Avg output tokens: {stats['avg_output_tokens']:.1f} | gen {stats['t_gen']:.1f}s train {stats['t_train']:.1f}s")


def log_eval(metrics: Dict[str, Any], writer: SummaryWriter, step: int) -> None:
    for k in EVAL_KEYS:
        writer.add_scalar(f"eval/{k}", metrics[k], global_step=step)
    with open(os.path.join(writer.get_logdir(), "eval_metrics.jsonl"), "a") as f:
        f.write(json.dumps({"step": step, **{k: metrics[k] for k in EVAL_KEYS}}) + "\n")
    tol = 1e-8
    examples = metrics.get("examples", []) or []
    groups = {"CORRECT, reward=1.0": [ex for ex in examples if abs(float(ex["reward"]) - 1.0) < tol][:10],
              "PARTIAL, reward=0.1": [ex for ex in examples if abs(float(ex["reward"]) - 0.1) < tol][:10],
              "FAILED, reward=0.0": [ex for ex in examples if abs(float(ex["reward"]) - 0.0) < tol][:10]}
    for name, exs in groups.items():
        if exs:
            print(f"\n=== Eval examples ({name}) @ step {step} ===")
            for idx, ex in enumerate(exs[:2], 1):
                print(f"[#{idx}]\n" + _format_eval_example(ex))
            writer.add_text(f"eval/examples_{name.split(',')[0].lower()}", "\n\n".join(_format_eval_example(ex) for ex in exs),
                            global_step=step)
    print(f"Eval @ step {step}: accuracy={metrics['accuracy']:.1f}% mean_reward={metrics['mean_reward']:.4f} "
          f"avg_tokens={metrics['avg_output_tokens']:.1f} | correct:{metrics['count_correct']} "
          f"partial:{metrics['count_partial']} failed:{metrics['count_failed']}")


